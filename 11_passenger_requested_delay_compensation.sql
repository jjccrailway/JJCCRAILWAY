-- JJCC Railways: passenger-requested delay compensation with Admin approval
-- Run AFTER migration 10. This changes delay incidents to record verified arrival only.
-- JCoins are credited only after an Admin/Super Admin approves a passenger request.

BEGIN;

CREATE TABLE IF NOT EXISTS public.delay_compensation_requests (
  request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id bigint NOT NULL REFERENCES public.train_delay_incidents(incident_id) ON DELETE RESTRICT,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  booking_reference text NOT NULL,
  original_fare numeric(12,2) NOT NULL CHECK (original_fare > 0),
  compensation_percent numeric(5,2) NOT NULL CHECK (compensation_percent IN (25,50,100)),
  compensation_amount numeric(12,2) NOT NULL CHECK (compensation_amount > 0),
  request_status text NOT NULL DEFAULT 'pending' CHECK (request_status IN ('pending','approved','rejected')),
  requested_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  admin_note text,
  UNIQUE (booking_id, incident_id)
);

CREATE INDEX IF NOT EXISTS delay_comp_requests_status_idx
  ON public.delay_compensation_requests(request_status, requested_at DESC);
CREATE INDEX IF NOT EXISTS delay_comp_requests_user_idx
  ON public.delay_compensation_requests(user_id, requested_at DESC);

ALTER TABLE public.delay_compensation_requests ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Passengers and staff read delay compensation requests" ON public.delay_compensation_requests;
CREATE POLICY "Passengers and staff read delay compensation requests"
ON public.delay_compensation_requests FOR SELECT TO authenticated
USING (user_id = auth.uid()
  OR COALESCE(public.current_user_role()::text,'') IN ('admin','super_admin'));
GRANT SELECT ON public.delay_compensation_requests TO authenticated;
REVOKE ALL ON public.delay_compensation_requests FROM anon;

-- Staff records the verified arrival and incident only. It never credits wallets.
CREATE OR REPLACE FUNCTION public.record_train_delay_incident(
  p_train_id bigint,
  p_travel_date date,
  p_arrival_station_id bigint,
  p_actual_arrival_at timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $function$
DECLARE
  v_role text := public.current_user_role()::text;
  v_scheduled timestamptz;
  v_delay integer;
  v_percent numeric(5,2);
  v_incident_id bigint;
BEGIN
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN
    RAISE EXCEPTION 'Only authorized railway staff can record verified arrival data.';
  END IF;
  IF p_actual_arrival_at IS NULL THEN RAISE EXCEPTION 'Actual arrival timestamp is required.'; END IF;

  SELECT min((b.travel_date + b.arrival_time::time) AT TIME ZONE 'Asia/Manila')
    INTO v_scheduled
    FROM public.bookings b
   WHERE b.train_id=p_train_id AND b.travel_date=p_travel_date
     AND b.arrival_station_id=p_arrival_station_id
     AND lower(b.booking_status)='confirmed';
  IF v_scheduled IS NULL THEN
    RAISE EXCEPTION 'No confirmed bookings or scheduled arrival time found for this train, date, and destination.';
  END IF;

  v_delay := greatest(0, floor(extract(epoch FROM (p_actual_arrival_at-v_scheduled))/60)::integer);
  v_percent := CASE WHEN v_delay < 30 THEN 0 WHEN v_delay < 60 THEN 25 WHEN v_delay < 120 THEN 50 ELSE 100 END;

  INSERT INTO public.train_delay_incidents
    (train_id,travel_date,arrival_station_id,actual_arrival_at,delay_minutes,compensation_percent,recorded_by)
  VALUES (p_train_id,p_travel_date,p_arrival_station_id,p_actual_arrival_at,v_delay,v_percent,auth.uid())
  ON CONFLICT (train_id,travel_date,arrival_station_id) DO NOTHING
  RETURNING incident_id INTO v_incident_id;
  IF v_incident_id IS NULL THEN
    RAISE EXCEPTION 'A delay incident has already been recorded for this train, date, and destination.';
  END IF;

  RETURN jsonb_build_object(
    'incident_id',v_incident_id,'delay_minutes',v_delay,
    'compensation_percent',v_percent,'credited_bookings',0,
    'message',CASE WHEN v_percent=0 THEN 'Arrival recorded. No compensation is due below 30 minutes.'
      ELSE 'Arrival recorded. Eligible passengers may now submit a compensation request for Admin review.' END
  );
END;
$function$;

-- Passenger submits an optional claim for their own confirmed booking.
CREATE OR REPLACE FUNCTION public.request_delay_compensation(p_booking_reference text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $function$
DECLARE
  v_user uuid := auth.uid();
  v_booking public.bookings%ROWTYPE;
  v_incident public.train_delay_incidents%ROWTYPE;
  v_amount numeric(12,2);
  v_request_id bigint;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in to request delay compensation.'; END IF;

  SELECT * INTO v_booking FROM public.bookings
   WHERE booking_reference=upper(btrim(p_booking_reference)) AND user_id=v_user
   FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found for your account.'; END IF;
  IF lower(v_booking.booking_status) <> 'confirmed' THEN
    RAISE EXCEPTION 'Only confirmed bookings are eligible to request delay compensation.';
  END IF;

  SELECT * INTO v_incident FROM public.train_delay_incidents
   WHERE train_id=v_booking.train_id
     AND travel_date=v_booking.travel_date
     AND arrival_station_id=v_booking.arrival_station_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Verified arrival data is not available yet. Please check again later.'; END IF;
  IF v_incident.compensation_percent <= 0 THEN
    RAISE EXCEPTION 'This delay does not qualify for compensation.';
  END IF;

  v_amount := round(COALESCE(v_booking.total_fare,0)*v_incident.compensation_percent/100.0,2);
  IF v_amount <= 0 THEN RAISE EXCEPTION 'The calculated compensation amount is invalid.'; END IF;

  INSERT INTO public.delay_compensation_requests
    (incident_id,booking_id,user_id,booking_reference,original_fare,
     compensation_percent,compensation_amount)
  VALUES (v_incident.incident_id,v_booking.booking_id,v_user,v_booking.booking_reference,
          v_booking.total_fare,v_incident.compensation_percent,v_amount)
  ON CONFLICT (booking_id,incident_id) DO NOTHING
  RETURNING request_id INTO v_request_id;

  IF v_request_id IS NULL THEN
    SELECT request_id INTO v_request_id FROM public.delay_compensation_requests
     WHERE booking_id=v_booking.booking_id AND incident_id=v_incident.incident_id;
    RETURN jsonb_build_object('request_id',v_request_id,'status','already_requested',
      'message','A compensation request for this booking and delay incident already exists.');
  END IF;

  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  VALUES(v_user,v_booking.booking_id,'Delay compensation request submitted',
    'Your delay compensation request has been submitted and is awaiting Admin review. No JCoins have been credited yet.','info');

  RETURN jsonb_build_object('request_id',v_request_id,'status','pending',
    'compensation_percent',v_incident.compensation_percent,
    'compensation_amount',v_amount,'message','Your request has been submitted for Admin approval.');
END;
$function$;

-- Admin decision; approval and JCoins ledger credit are one atomic transaction.
CREATE OR REPLACE FUNCTION public.review_delay_compensation_request(
  p_request_id bigint,
  p_decision text,
  p_admin_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $function$
DECLARE
  v_role text := public.current_user_role()::text;
  v_req public.delay_compensation_requests%ROWTYPE;
  v_balance numeric(12,2);
  v_tx bigint;
BEGIN
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN
    RAISE EXCEPTION 'Only Admin or Super Admin can review compensation requests.';
  END IF;
  IF lower(COALESCE(p_decision,'')) NOT IN ('approved','rejected') THEN
    RAISE EXCEPTION 'Decision must be approved or rejected.';
  END IF;

  SELECT * INTO v_req FROM public.delay_compensation_requests
   WHERE request_id=p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Compensation request not found.'; END IF;
  IF v_req.request_status <> 'pending' THEN
    RAISE EXCEPTION 'This request has already been reviewed.';
  END IF;

  IF lower(p_decision)='rejected' THEN
    UPDATE public.delay_compensation_requests
       SET request_status='rejected',reviewed_by=auth.uid(),reviewed_at=now(),
           admin_note=NULLIF(btrim(p_admin_note),'')
     WHERE request_id=p_request_id;
    INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
    VALUES(v_req.user_id,v_req.booking_id,'Delay compensation request declined',
      'Your delay compensation request was not approved. Please check your booking or contact support for details.','warning');
    RETURN jsonb_build_object('request_id',p_request_id,'status','rejected','credited',false);
  END IF;

  UPDATE public.delay_compensation_requests
     SET request_status='approved',reviewed_by=auth.uid(),reviewed_at=now(),
         admin_note=NULLIF(btrim(p_admin_note),'')
   WHERE request_id=p_request_id;

  INSERT INTO public.jcoins_wallets(user_id) VALUES(v_req.user_id)
  ON CONFLICT(user_id) DO NOTHING;
  SELECT balance INTO v_balance FROM public.jcoins_wallets
   WHERE user_id=v_req.user_id FOR UPDATE;
  v_balance := v_balance + v_req.compensation_amount;
  UPDATE public.jcoins_wallets
     SET balance=v_balance,total_earned=total_earned+v_req.compensation_amount,updated_at=now()
   WHERE user_id=v_req.user_id;

  INSERT INTO public.jcoins_transactions
    (user_id,transaction_type,direction,amount,balance_after,booking_id,
     booking_reference,description,idempotency_key,created_by)
  VALUES
    (v_req.user_id,'DELAY_COMPENSATION','credit',v_req.compensation_amount,v_balance,
     v_req.booking_id,v_req.booking_reference,
     'Admin-approved delay compensation ('||v_req.compensation_percent::text||'%).',
     'delay-compensation-request:'||v_req.request_id::text,auth.uid())
  RETURNING transaction_id INTO v_tx;

  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  VALUES(v_req.user_id,v_req.booking_id,'Delay compensation approved',
    v_req.compensation_amount::text||' JCoins have been credited to your wallet.','success');

  RETURN jsonb_build_object('request_id',p_request_id,'status','approved',
    'credited',true,'amount',v_req.compensation_amount,'jcoins_balance',v_balance,
    'transaction_id',v_tx);
END;
$function$;

REVOKE ALL ON FUNCTION public.request_delay_compensation(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.request_delay_compensation(text) TO authenticated;
REVOKE ALL ON FUNCTION public.review_delay_compensation_request(bigint,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.review_delay_compensation_request(bigint,text,text) TO authenticated;
REVOKE ALL ON FUNCTION public.record_train_delay_incident(bigint,date,bigint,timestamptz) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_train_delay_incident(bigint,date,bigint,timestamptz) TO authenticated;

COMMENT ON FUNCTION public.record_train_delay_incident(bigint,date,bigint,timestamptz) IS
  'Admin records verified arrival and calculates eligibility only; no wallet credit is issued.';
COMMENT ON FUNCTION public.request_delay_compensation(text) IS
  'Passenger submits an optional delay compensation request for their own eligible confirmed booking.';
COMMENT ON FUNCTION public.review_delay_compensation_request(bigint,text,text) IS
  'Admin approves or rejects a passenger request; JCoins credit occurs only on approval.';

COMMIT;
