CREATE TABLE IF NOT EXISTS public.generated_return_services (
  generated_return_service_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_train_id bigint NOT NULL REFERENCES public.trains(train_id) ON DELETE CASCADE,
  generated_train_id bigint NULL UNIQUE REFERENCES public.trains(train_id) ON DELETE CASCADE,
  travel_date date NOT NULL,
  departure_station_id bigint NOT NULL REFERENCES public.stations(station_id),
  arrival_station_id bigint NOT NULL REFERENCES public.stations(station_id),
  departure_slot time without time zone NOT NULL,
  arrival_time time without time zone NULL,
  duration_minutes integer NULL,
  return_fare numeric(10,2) NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT generated_return_services_route_slot_key
    UNIQUE (source_train_id, travel_date, departure_station_id, arrival_station_id, departure_slot)
);

CREATE INDEX IF NOT EXISTS generated_return_services_date_route_idx
  ON public.generated_return_services(travel_date, departure_station_id, arrival_station_id);

ALTER TABLE public.generated_return_services ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.generate_round_trip_return_services(
  p_outbound_train_code text,
  p_outbound_departure_code text,
  p_outbound_arrival_code text,
  p_return_travel_date date
)
RETURNS TABLE (
  train_code text,
  train_name text,
  train_type text,
  total_seats integer,
  departure_time time without time zone,
  arrival_time time without time zone,
  duration_minutes integer,
  return_fare numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_user_id uuid := auth.uid();
  v_source_train_id bigint;
  v_source_train_name varchar(100);
  v_source_train_type varchar(50);
  v_total_seats integer;
  v_from_order integer;
  v_to_order integer;
  v_station_ids bigint[];
  v_arrival_times time without time zone[];
  v_departure_times time without time zone[];
  v_fares numeric[];
  v_stop_count integer;
  v_return_fare numeric(10,2) := 0;
  v_index integer;
  v_slot_minute integer;
  v_slot_time time without time zone;
  v_arrival_time time without time zone;
  v_duration_minutes integer;
  v_service_id bigint;
  v_generated_train_id bigint;
  v_train_code varchar(20);
  v_new_train_id bigint;
  v_new_arrival_time time without time zone;
  v_new_departure_time time without time zone;
  v_edge_start time without time zone;
  v_edge_end time without time zone;
  v_edge_minutes integer;
  v_dwell_minutes integer;
  v_arrival_offset integer;
  v_departure_offset integer;
  v_current_offset integer;
  v_original_index integer;
  v_j integer;
  v_new_fare numeric(10,2);
  v_seat_count integer;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Please sign in before generating return schedules.';
  END IF;

  IF p_return_travel_date IS NULL
     OR p_return_travel_date < (pg_catalog.now() AT TIME ZONE 'Asia/Manila')::date THEN
    RAISE EXCEPTION 'Please choose a valid return travel date.';
  END IF;

  SELECT t.train_id, t.train_name, t.train_type, t.total_seats
    INTO v_source_train_id, v_source_train_name, v_source_train_type, v_total_seats
    FROM public.trains t
   WHERE t.train_code = pg_catalog.upper(pg_catalog.btrim(p_outbound_train_code))
     AND t.is_active = true;

  IF v_source_train_id IS NULL THEN
    RAISE EXCEPTION 'The selected outbound train is no longer active.';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      v_source_train_id::text || ':' || p_return_travel_date::text || ':' ||
      pg_catalog.upper(pg_catalog.btrim(p_outbound_departure_code)) || ':' ||
      pg_catalog.upper(pg_catalog.btrim(p_outbound_arrival_code)),
      0
    )
  );

  SELECT ts.stop_order
    INTO v_from_order
    FROM public.train_stops ts
    JOIN public.stations s ON s.station_id = ts.station_id
   WHERE ts.train_id = v_source_train_id
     AND s.station_code = pg_catalog.upper(pg_catalog.btrim(p_outbound_departure_code))
     AND s.is_active = true;

  SELECT ts.stop_order
    INTO v_to_order
    FROM public.train_stops ts
    JOIN public.stations s ON s.station_id = ts.station_id
   WHERE ts.train_id = v_source_train_id
     AND s.station_code = pg_catalog.upper(pg_catalog.btrim(p_outbound_arrival_code))
     AND s.is_active = true;

  IF v_from_order IS NULL OR v_to_order IS NULL OR v_to_order <= v_from_order THEN
    RAISE EXCEPTION 'The selected outbound route is not valid for automatic return scheduling.';
  END IF;

  SELECT
    pg_catalog.array_agg(ts.station_id ORDER BY ts.stop_order),
    pg_catalog.array_agg(ts.arrival_time ORDER BY ts.stop_order),
    pg_catalog.array_agg(ts.departure_time ORDER BY ts.stop_order),
    pg_catalog.array_agg(ts.fare_from_previous ORDER BY ts.stop_order)
  INTO v_station_ids, v_arrival_times, v_departure_times, v_fares
  FROM public.train_stops ts
  WHERE ts.train_id = v_source_train_id
    AND ts.stop_order BETWEEN v_from_order AND v_to_order;

  v_stop_count := COALESCE(pg_catalog.array_length(v_station_ids, 1), 0);
  IF v_stop_count < 2 THEN
    RAISE EXCEPTION 'The selected route does not contain enough scheduled stops.';
  END IF;

  IF v_departure_times[1] IS NULL OR v_arrival_times[v_stop_count] IS NULL THEN
    RAISE EXCEPTION 'The selected train is missing departure or arrival times needed to generate its return timetable.';
  END IF;

  v_duration_minutes := FLOOR(
    EXTRACT(EPOCH FROM (v_arrival_times[v_stop_count] - v_departure_times[1])) / 60
  )::integer;
  IF v_duration_minutes < 0 THEN
    v_duration_minutes := v_duration_minutes + 1440;
  END IF;
  IF v_duration_minutes <= 0 THEN
    RAISE EXCEPTION 'The selected train has an invalid journey duration.';
  END IF;

  FOR v_index IN 2..v_stop_count LOOP
    IF v_fares[v_index] IS NULL THEN
      RAISE EXCEPTION 'Fare information is incomplete for the selected route.';
    END IF;
    v_return_fare := v_return_fare + v_fares[v_index];
  END LOOP;

  -- Generate eight services per day, beginning at 06:00 and repeating every
  -- two hours. Existing rows are reused so repeated searches do not duplicate
  -- train, stop, or seat records.
  FOR v_slot_minute IN
    SELECT gs.slot_minute
      FROM pg_catalog.generate_series(360, 1200, 120) AS gs(slot_minute)
  LOOP
    v_slot_time := (time '00:00' + v_slot_minute * interval '1 minute')::time;
    v_arrival_time := (
      time '00:00' + (((v_slot_minute + v_duration_minutes) % 1440) * interval '1 minute')
    )::time;

    INSERT INTO public.generated_return_services (
      source_train_id, travel_date, departure_station_id, arrival_station_id,
      departure_slot, arrival_time, duration_minutes, return_fare
    )
    VALUES (
      v_source_train_id, p_return_travel_date,
      v_station_ids[v_stop_count], v_station_ids[1],
      v_slot_time, v_arrival_time, v_duration_minutes, v_return_fare
    )
    ON CONFLICT (
      source_train_id, travel_date, departure_station_id, arrival_station_id, departure_slot
    ) DO NOTHING;

    SELECT grs.generated_return_service_id, grs.generated_train_id
      INTO v_service_id, v_generated_train_id
      FROM public.generated_return_services grs
     WHERE grs.source_train_id = v_source_train_id
       AND grs.travel_date = p_return_travel_date
       AND grs.departure_station_id = v_station_ids[v_stop_count]
       AND grs.arrival_station_id = v_station_ids[1]
       AND grs.departure_slot = v_slot_time;

    IF v_generated_train_id IS NULL THEN
      v_train_code := ('RTG-' || pg_catalog.lpad(v_service_id::text, 15, '0'))::varchar(20);

      INSERT INTO public.trains (
        train_code, train_name, train_type, total_seats, is_active, train_status
      )
      VALUES (
        v_train_code,
        pg_catalog.left(COALESCE(v_source_train_name, 'JJCC Railways') || ' Generated Return', 100),
        COALESCE(v_source_train_type, 'Generated Return'),
        v_total_seats,
        true,
        'active'
      )
      RETURNING train_id INTO v_new_train_id;

      v_current_offset := 0;
      FOR v_j IN 1..v_stop_count LOOP
        v_original_index := v_stop_count - v_j + 1;

        IF v_j = 1 THEN
          v_new_arrival_time := NULL;
          v_new_departure_time := v_slot_time;
          v_current_offset := 0;
        ELSE
          v_edge_start := COALESCE(v_departure_times[v_original_index], v_arrival_times[v_original_index]);
          v_edge_end := COALESCE(v_arrival_times[v_original_index + 1], v_departure_times[v_original_index + 1]);
          IF v_edge_start IS NULL OR v_edge_end IS NULL THEN
            RAISE EXCEPTION 'A stop is missing timing data needed to generate the return timetable.';
          END IF;

          v_edge_minutes := FLOOR(EXTRACT(EPOCH FROM (v_edge_end - v_edge_start)) / 60)::integer;
          IF v_edge_minutes < 0 THEN
            v_edge_minutes := v_edge_minutes + 1440;
          END IF;
          IF v_edge_minutes <= 0 THEN
            RAISE EXCEPTION 'The source timetable contains an invalid stop-to-stop travel time.';
          END IF;

          v_arrival_offset := v_current_offset + v_edge_minutes;
          v_new_arrival_time := (
            time '00:00' + (((v_slot_minute + v_arrival_offset) % 1440) * interval '1 minute')
          )::time;

          v_dwell_minutes := 0;
          IF v_j < v_stop_count
             AND v_arrival_times[v_original_index] IS NOT NULL
             AND v_departure_times[v_original_index] IS NOT NULL THEN
            v_dwell_minutes := FLOOR(
              EXTRACT(EPOCH FROM (v_departure_times[v_original_index] - v_arrival_times[v_original_index])) / 60
            )::integer;
            IF v_dwell_minutes < 0 THEN
              v_dwell_minutes := v_dwell_minutes + 1440;
            END IF;
          END IF;

          IF v_j < v_stop_count THEN
            v_departure_offset := v_arrival_offset + v_dwell_minutes;
            v_new_departure_time := (
              time '00:00' + (((v_slot_minute + v_departure_offset) % 1440) * interval '1 minute')
            )::time;
            v_current_offset := v_departure_offset;
          ELSE
            v_new_departure_time := NULL;
            v_current_offset := v_arrival_offset;
          END IF;
        END IF;

        v_new_fare := CASE
          WHEN v_j = 1 THEN 0
          ELSE COALESCE(v_fares[v_original_index + 1], 0)
        END;

        INSERT INTO public.train_stops (
          train_id, station_id, stop_order, arrival_time, departure_time, fare_from_previous
        )
        VALUES (
          v_new_train_id,
          v_station_ids[v_original_index],
          v_j,
          v_new_arrival_time,
          v_new_departure_time,
          v_new_fare
        );
      END LOOP;

      INSERT INTO public.train_seats (
        train_id, coach_code, seat_number, seat_type, is_active
      )
      SELECT
        v_new_train_id, ts.coach_code, ts.seat_number, ts.seat_type, ts.is_active
      FROM public.train_seats ts
      WHERE ts.train_id = v_source_train_id;

      GET DIAGNOSTICS v_seat_count = ROW_COUNT;
      IF v_seat_count = 0 THEN
        RAISE EXCEPTION 'The selected train has no configured seats to copy to its return service.';
      END IF;

      UPDATE public.generated_return_services grs
         SET generated_train_id = v_new_train_id,
             arrival_time = v_new_arrival_time,
             duration_minutes = v_current_offset
       WHERE grs.generated_return_service_id = v_service_id;
    END IF;
  END LOOP;

  RETURN QUERY
  SELECT
    t.train_code::text,
    t.train_name::text,
    t.train_type::text,
    t.total_seats,
    grs.departure_slot,
    grs.arrival_time,
    grs.duration_minutes,
    grs.return_fare::numeric
  FROM public.generated_return_services grs
  JOIN public.trains t ON t.train_id = grs.generated_train_id
  WHERE grs.source_train_id = v_source_train_id
    AND grs.travel_date = p_return_travel_date
    AND grs.departure_station_id = v_station_ids[v_stop_count]
    AND grs.arrival_station_id = v_station_ids[1]
  ORDER BY grs.departure_slot;
END;
$function$;

REVOKE ALL ON FUNCTION public.generate_round_trip_return_services(text, text, text, date)
  FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.generate_round_trip_return_services(text, text, text, date)
  TO authenticated;

COMMIT;
