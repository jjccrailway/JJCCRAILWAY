-- JJCC Railways: JCoins wallet foundation
-- PR 01 | Run once in Supabase SQL Editor after backing up the database.
-- This migration creates one wallet per Auth account and an append-only ledger.
-- It does NOT yet enable booking debits, refunds, compensation, or admin adjustments.
-- Those workflows will be added in later migrations using atomic SECURITY DEFINER RPCs.

BEGIN;

CREATE TABLE IF NOT EXISTS public.jcoins_wallets (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  balance numeric(12,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
  total_earned numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_earned >= 0),
  total_spent numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_spent >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.jcoins_transactions (
  transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  transaction_type text NOT NULL CHECK (
    transaction_type IN (
      'REFUND_CREDIT',
      'DELAY_COMPENSATION',
      'BOOKING_PAYMENT',
      'BOOKING_PAYMENT_REVERSAL',
      'ADMIN_ADJUSTMENT'
    )
  ),
  direction text NOT NULL CHECK (direction IN ('credit','debit')),
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  balance_after numeric(12,2) NOT NULL CHECK (balance_after >= 0),
  booking_id bigint REFERENCES public.bookings(booking_id) ON DELETE SET NULL,
  booking_reference text,
  description text,
  idempotency_key text UNIQUE,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS jcoins_transactions_user_created_idx
  ON public.jcoins_transactions(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS jcoins_transactions_booking_idx
  ON public.jcoins_transactions(booking_id)
  WHERE booking_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS jcoins_transactions_type_idx
  ON public.jcoins_transactions(transaction_type, created_at DESC);

-- Automatically provision a zero-balance wallet for new registered accounts.
CREATE OR REPLACE FUNCTION public.create_jcoins_wallet_for_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  INSERT INTO public.jcoins_wallets(user_id)
  VALUES (NEW.id)
  ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS on_auth_user_created_jcoins_wallet ON auth.users;
CREATE TRIGGER on_auth_user_created_jcoins_wallet
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.create_jcoins_wallet_for_new_user();

-- Provision wallets for accounts that already exist.
INSERT INTO public.jcoins_wallets(user_id)
SELECT id FROM auth.users
ON CONFLICT (user_id) DO NOTHING;

-- Wallet and ledger are readable only by their owner and authorized staff.
ALTER TABLE public.jcoins_wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jcoins_transactions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "JCoins wallet owner or staff can read" ON public.jcoins_wallets;
CREATE POLICY "JCoins wallet owner or staff can read"
ON public.jcoins_wallets
FOR SELECT TO authenticated
USING (
  user_id = auth.uid()
  OR COALESCE(public.current_user_role()::text, '') IN ('admin','super_admin')
);

DROP POLICY IF EXISTS "JCoins transactions owner or staff can read" ON public.jcoins_transactions;
CREATE POLICY "JCoins transactions owner or staff can read"
ON public.jcoins_transactions
FOR SELECT TO authenticated
USING (
  user_id = auth.uid()
  OR COALESCE(public.current_user_role()::text, '') IN ('admin','super_admin')
);

-- No direct client-side inserts, updates, or deletes are granted.
REVOKE ALL ON public.jcoins_wallets FROM anon, authenticated;
REVOKE ALL ON public.jcoins_transactions FROM anon, authenticated;
GRANT SELECT ON public.jcoins_wallets TO authenticated;
GRANT SELECT ON public.jcoins_transactions TO authenticated;
REVOKE ALL ON FUNCTION public.create_jcoins_wallet_for_new_user() FROM PUBLIC, anon, authenticated;

COMMENT ON TABLE public.jcoins_wallets IS
  'One JCoins wallet per Supabase Auth account. Balance changes must be performed by trusted database RPCs.';
COMMENT ON TABLE public.jcoins_transactions IS
  'Append-only audit ledger for JCoins credits and debits. Never edit wallet balances directly from the browser.';
COMMENT ON COLUMN public.jcoins_wallets.balance IS 'Current JCoins balance; 1 PHP = 1 JCoin.';
COMMENT ON COLUMN public.jcoins_wallets.total_earned IS 'Lifetime JCoins credits, including refunds and compensation.';
COMMENT ON COLUMN public.jcoins_wallets.total_spent IS 'Lifetime JCoins debits for bookings and other approved uses.';

COMMIT;
