-- JJCC Railways Discount ID Verification & Fare Rules
-- Run AFTER existing migrations 01-14. Back up production first.
BEGIN;

ALTER TABLE public.passengers ALTER COLUMN passenger_type SET DEFAULT 'regular';

CREATE TABLE IF NOT EXISTS public.discount_id_submissions (
  discount_submission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  passenger_id bigint NOT NULL REFERENCES public.passengers(passenger_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  id_path text NOT NULL,
  claimed_type text NOT NULL CHECK (claimed_type IN ('student','senior','pwd')),
  status text NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review','approved','rejected')),
  admin_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id),
  notification_sent_at timestamptz,
  UNIQUE (passenger_id)
);
CREATE INDEX IF NOT EXISTS discount_id_submissions_status_idx ON public.discount_id_submissions(status, submitted_at DESC);
ALTER TABLE public.discount_id_submissions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users read own discount ID submissions" ON public.discount_id_submissions;
CREATE POLICY "Users read own discount ID submissions" ON public.discount_id_submissions FOR SELECT TO authenticated USING (user_id = auth.uid());
DROP POLICY IF EXISTS "Staff read discount ID submissions" ON public.discount_id_submissions;
CREATE POLICY "Staff read discount ID submissions" ON public.discount_id_submissions FOR SELECT TO authenticated USING (public.current_user_role() IN ('admin','super_admin'));
DROP POLICY IF EXISTS "Users submit own discount IDs" ON public.discount_id_submissions;
CREATE POLICY "Users submit own discount IDs" ON public.discount_id_submissions FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid() AND EXISTS (SELECT 1 FROM public.bookings b WHERE b.booking_id = discount_id_submissions.booking_id AND b.user_id = auth.uid() AND b.booking_status = 'pending_discount_verification'));

INSERT INTO storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
VALUES ('discount-ids','discount-ids',false,5242880,ARRAY['image/jpeg','image/png','image/webp','application/pdf'])
ON CONFLICT (id) DO UPDATE SET public=false,file_size_limit=5242880,allowed_mime_types=EXCLUDED.allowed_mime_types;
DROP POLICY IF EXISTS "Users upload own discount IDs" ON storage.objects;
CREATE POLICY "Users upload own discount IDs" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id='discount-ids' AND (storage.foldername(name))[1]=auth.uid()::text);
DROP POLICY IF EXISTS "Users and staff view discount IDs" ON storage.objects;
CREATE POLICY "Users and staff view discount IDs" ON storage.objects FOR SELECT TO authenticated USING (bucket_id='discount-ids' AND ((storage.foldername(name))[1]=auth.uid()::text OR public.current_user_role() IN ('admin','super_admin')));
