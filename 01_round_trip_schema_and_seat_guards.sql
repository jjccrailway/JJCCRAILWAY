-- JJCC Railways Round Trip migration - split execution
-- Part 1 of 3: booking columns, return passenger table, RLS, and seat-overlap guards.
-- Run this file as one complete query in Supabase SQL Editor.

BEGIN;

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS trip_type text NOT NULL DEFAULT 'one_way',
  ADD COLUMN IF NOT EXISTS return_train_id bigint NULL REFERENCES public.trains(train_id),
  ADD COLUMN IF NOT EXISTS return_departure_station_id bigint NULL REFERENCES public.stations(station_id),
  ADD COLUMN IF NOT EXISTS return_arrival_station_id bigint NULL REFERENCES public.stations(station_id),
  ADD COLUMN IF NOT EXISTS return_travel_date date NULL,
  ADD COLUMN IF NOT EXISTS return_departure_time time without time zone NULL,
  ADD COLUMN IF NOT EXISTS return_arrival_time time without time zone NULL,
  ADD COLUMN IF NOT EXISTS return_fare numeric(10,2) NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'bookings_trip_type_check'
      AND conrelid = 'public.bookings'::regclass
  ) THEN
    ALTER TABLE public.bookings
      ADD CONSTRAINT bookings_trip_type_check
      CHECK (trip_type IN ('one_way', 'round_trip'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'bookings_return_route_check'
      AND conrelid = 'public.bookings'::regclass
  ) THEN
    ALTER TABLE public.bookings
      ADD CONSTRAINT bookings_return_route_check
      CHECK (
        (trip_type = 'one_way'
          AND return_train_id IS NULL
          AND return_departure_station_id IS NULL
          AND return_arrival_station_id IS NULL
          AND return_travel_date IS NULL
          AND return_departure_time IS NULL
          AND return_arrival_time IS NULL
          AND return_fare IS NULL)
        OR
        (trip_type = 'round_trip'
          AND return_train_id IS NOT NULL
          AND return_departure_station_id IS NOT NULL
          AND return_arrival_station_id IS NOT NULL
          AND return_travel_date IS NOT NULL
          AND return_departure_time IS NOT NULL
          AND return_arrival_time IS NOT NULL
          AND return_fare IS NOT NULL)
      );
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS bookings_return_train_date_idx
  ON public.bookings(return_train_id, return_travel_date)
  WHERE return_train_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.booking_return_passengers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  passenger_id bigint NOT NULL REFERENCES public.passengers(passenger_id) ON DELETE CASCADE,
  seat_number varchar(20) NOT NULL,
  CONSTRAINT booking_return_passengers_booking_passenger_key UNIQUE (booking_id, passenger_id)
);

CREATE INDEX IF NOT EXISTS booking_return_passengers_booking_idx
  ON public.booking_return_passengers(booking_id);

ALTER TABLE public.booking_return_passengers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users and staff can view return seat assignments"
  ON public.booking_return_passengers;

CREATE POLICY "Users and staff can view return seat assignments"
  ON public.booking_return_passengers
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.bookings b
      WHERE b.booking_id = booking_return_passengers.booking_id
        AND (
          b.user_id = auth.uid()
          OR public.current_user_role() IN ('admin', 'super_admin')
        )
    )
  );

GRANT SELECT ON public.booking_return_passengers TO authenticated;


-- Database-level cross-checks prevent an outbound booking from taking a seat
-- that is already held by a round-trip return leg (and vice versa).
CREATE OR REPLACE FUNCTION public.guard_round_trip_seat_overlap()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_train_id bigint;
  v_travel_date date;
  v_departure_station_id bigint;
  v_arrival_station_id bigint;
  v_departure_order integer;
  v_arrival_order integer;
BEGIN
  IF TG_TABLE_NAME = 'booking_passengers' THEN
    SELECT b.train_id, b.travel_date, b.departure_station_id, b.arrival_station_id
      INTO v_train_id, v_travel_date, v_departure_station_id, v_arrival_station_id
      FROM public.bookings b
     WHERE b.booking_id = NEW.booking_id;
  ELSE
    SELECT b.return_train_id, b.return_travel_date,
           b.return_departure_station_id, b.return_arrival_station_id
      INTO v_train_id, v_travel_date, v_departure_station_id, v_arrival_station_id
      FROM public.bookings b
     WHERE b.booking_id = NEW.booking_id;
  END IF;

  IF v_train_id IS NULL OR v_travel_date IS NULL THEN
    RETURN NEW;
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_train_id::text || ':' || v_travel_date::text, 0)
  );

  SELECT ts.stop_order INTO v_departure_order
    FROM public.train_stops ts
   WHERE ts.train_id = v_train_id
     AND ts.station_id = v_departure_station_id;

  SELECT ts.stop_order INTO v_arrival_order
    FROM public.train_stops ts
   WHERE ts.train_id = v_train_id
     AND ts.station_id = v_arrival_station_id;

  IF v_departure_order IS NULL OR v_arrival_order IS NULL
     OR v_arrival_order <= v_departure_order THEN
    RAISE EXCEPTION 'Invalid route for seat reservation.';
  END IF;

  IF TG_TABLE_NAME = 'booking_passengers' THEN
    IF EXISTS (
      SELECT 1
        FROM public.booking_return_passengers brp
        JOIN public.bookings b ON b.booking_id = brp.booking_id
        JOIN public.train_stops booked_from
          ON booked_from.train_id = b.return_train_id
         AND booked_from.station_id = b.return_departure_station_id
        JOIN public.train_stops booked_to
          ON booked_to.train_id = b.return_train_id
         AND booked_to.station_id = b.return_arrival_station_id
       WHERE b.return_train_id = v_train_id
         AND b.return_travel_date = v_travel_date
         AND pg_catalog.lower(b.booking_status) NOT IN ('cancelled','refunded','expired')
         AND brp.seat_number = NEW.seat_number
         AND booked_from.stop_order < v_arrival_order
         AND booked_to.stop_order > v_departure_order
    ) THEN
      RAISE EXCEPTION 'Seat % is already reserved for a return journey.', NEW.seat_number;
    END IF;
  ELSE
    IF EXISTS (
      SELECT 1
        FROM public.booking_passengers bp
        JOIN public.bookings b ON b.booking_id = bp.booking_id
        JOIN public.train_stops booked_from
          ON booked_from.train_id = b.train_id
         AND booked_from.station_id = b.departure_station_id
        JOIN public.train_stops booked_to
          ON booked_to.train_id = b.train_id
         AND booked_to.station_id = b.arrival_station_id
       WHERE b.train_id = v_train_id
         AND b.travel_date = v_travel_date
         AND pg_catalog.lower(b.booking_status) NOT IN ('cancelled','refunded','expired')
         AND bp.seat_number = NEW.seat_number
         AND booked_from.stop_order < v_arrival_order
         AND booked_to.stop_order > v_departure_order
    ) THEN
      RAISE EXCEPTION 'Seat % is already occupied on this journey.', NEW.seat_number;
    END IF;

    IF EXISTS (
      SELECT 1
        FROM public.booking_return_passengers brp
        JOIN public.bookings b ON b.booking_id = brp.booking_id
        JOIN public.train_stops booked_from
          ON booked_from.train_id = b.return_train_id
         AND booked_from.station_id = b.return_departure_station_id
        JOIN public.train_stops booked_to
          ON booked_to.train_id = b.return_train_id
         AND booked_to.station_id = b.return_arrival_station_id
       WHERE b.return_train_id = v_train_id
         AND b.return_travel_date = v_travel_date
         AND pg_catalog.lower(b.booking_status) NOT IN ('cancelled','refunded','expired')
         AND brp.seat_number = NEW.seat_number
         AND booked_from.stop_order < v_arrival_order
         AND booked_to.stop_order > v_departure_order
    ) THEN
      RAISE EXCEPTION 'Seat % is already reserved for another return journey.', NEW.seat_number;
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_guard_outbound_against_return_seats ON public.booking_passengers;
CREATE TRIGGER trg_guard_outbound_against_return_seats
BEFORE INSERT OR UPDATE OF booking_id, seat_number ON public.booking_passengers
FOR EACH ROW EXECUTE FUNCTION public.guard_round_trip_seat_overlap();

DROP TRIGGER IF EXISTS trg_guard_return_against_outbound_seats ON public.booking_return_passengers;
CREATE TRIGGER trg_guard_return_against_outbound_seats
BEFORE INSERT OR UPDATE OF booking_id, seat_number ON public.booking_return_passengers
FOR EACH ROW EXECUTE FUNCTION public.guard_round_trip_seat_overlap();

-- Returns seat numbers already occupied by return legs on the requested
-- train/date/route. Existing outbound reservations remain covered by the
-- existing get_available_seats() RPC.
CREATE OR REPLACE FUNCTION public.get_round_trip_reserved_seats(
  p_train_code text,
  p_departure_code text,
  p_arrival_code text,
  p_travel_date date
)
RETURNS TABLE(seat_number text)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_train_id bigint;
  v_departure_station_id bigint;
  v_arrival_station_id bigint;
  v_departure_order integer;
  v_arrival_order integer;
BEGIN
  SELECT t.train_id
    INTO v_train_id
    FROM public.trains t
   WHERE t.train_code = pg_catalog.upper(pg_catalog.btrim(p_train_code))
     AND t.is_active = true;

  IF v_train_id IS NULL THEN
    RAISE EXCEPTION 'Train not found or inactive.';
  END IF;

  SELECT ts.station_id, ts.stop_order
    INTO v_departure_station_id, v_departure_order
    FROM public.train_stops ts
    JOIN public.stations s ON s.station_id = ts.station_id
   WHERE ts.train_id = v_train_id
     AND s.station_code = pg_catalog.upper(pg_catalog.btrim(p_departure_code))
     AND s.is_active = true;

  SELECT ts.station_id, ts.stop_order
    INTO v_arrival_station_id, v_arrival_order
    FROM public.train_stops ts
    JOIN public.stations s ON s.station_id = ts.station_id
   WHERE ts.train_id = v_train_id
     AND s.station_code = pg_catalog.upper(pg_catalog.btrim(p_arrival_code))
     AND s.is_active = true;

  IF v_departure_station_id IS NULL
     OR v_arrival_station_id IS NULL
     OR v_arrival_order <= v_departure_order THEN
    RAISE EXCEPTION 'Invalid route direction.';
  END IF;

  RETURN QUERY
  SELECT DISTINCT brp.seat_number::text
    FROM public.booking_return_passengers brp
    JOIN public.bookings b ON b.booking_id = brp.booking_id
    JOIN public.train_stops booked_from
      ON booked_from.train_id = b.return_train_id
     AND booked_from.station_id = b.return_departure_station_id
    JOIN public.train_stops booked_to
      ON booked_to.train_id = b.return_train_id
     AND booked_to.station_id = b.return_arrival_station_id
   WHERE b.return_train_id = v_train_id
     AND b.return_travel_date = p_travel_date
     AND pg_catalog.lower(b.booking_status) NOT IN ('cancelled', 'refunded', 'expired')
     AND booked_from.stop_order < v_arrival_order
     AND booked_to.stop_order > v_departure_order;
END;
$function$;

REVOKE ALL ON FUNCTION public.get_round_trip_reserved_seats(text, text, text, date)
  FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_round_trip_reserved_seats(text, text, text, date)
  TO authenticated;

COMMIT;
