-- JJCC Railways: passenger-level discount verification and payment workflow
-- Run AFTER migrations 01-15_discount_id_verification.sql.
-- Back up production and test on a staging project first.
BEGIN;

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS passenger_payment_workflow boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.booking_passenger_workflow (
  workflow_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  passenger_id bigint NOT NULL REFERENCES public.passengers(passenger_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  passenger_type text NOT NULL CHECK (passenger_type IN ('regular','student','senior','pwd')),
  base_fare numeric(10,2) NOT NULL CHECK (base_fare >= 0),
  amount_due numeric(10,2) NOT NULL CHECK (amount_due >= 0),
  discount_status text NOT NULL CHECK (discount_status IN ('not_required','pending_review','approved','rejected')),
  payment_status text NOT NULL CHECK (payment_status IN ('awaiting_id','awaiting_payment','pending_review','paid','expired')),
  payment_deadline_at timestamptz,
  jcoins_amount numeric(10,2) NOT NULL DEFAULT 0,
  cash_due numeric(10,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (booking_id, passenger_id)
);
CREATE INDEX IF NOT EXISTS booking_passenger_workflow_booking_idx
  ON public.booking_passenger_workflow(booking_id, payment_status);
CREATE INDEX IF NOT EXISTS booking_passenger_workflow_deadline_idx
  ON public.booking_passenger_workflow(payment_deadline_at)
  WHERE payment_status = 'awaiting_payment';

CREATE TABLE IF NOT EXISTS public.passenger_payment_submissions (
  submission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_id bigint NOT NULL REFERENCES public.booking_passenger_workflow(workflow_id) ON DELETE CASCADE,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  passenger_id bigint NOT NULL REFERENCES public.passengers(passenger_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  receipt_path text NOT NULL,
  cash_amount numeric(10,2) NOT NULL DEFAULT 0,
  jcoins_amount numeric(10,2) NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review','approved','rejected')),
  admin_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id)
);
CREATE INDEX IF NOT EXISTS passenger_payment_submissions_status_idx
  ON public.passenger_payment_submissions(status, submitted_at DESC);

ALTER TABLE public.booking_passenger_workflow ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.passenger_payment_submissions ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.booking_passenger_workflow, public.passenger_payment_submissions TO authenticated;

DROP POLICY IF EXISTS "Passenger workflow owner or staff read" ON public.booking_passenger_workflow;
CREATE POLICY "Passenger workflow owner or staff read" ON public.booking_passenger_workflow
FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.current_user_role() IN ('admin','super_admin'));
DROP POLICY IF EXISTS "Passenger payment owner or staff read" ON public.passenger_payment_submissions;
CREATE POLICY "Passenger payment owner or staff read" ON public.passenger_payment_submissions
FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.current_user_role() IN ('admin','super_admin'));


-- Permit ID submissions for their own passenger row after workflow initialization.
DROP POLICY IF EXISTS "Users submit own discount IDs" ON public.discount_id_submissions;
CREATE POLICY "Users submit own discount IDs" ON public.discount_id_submissions
FOR INSERT TO authenticated WITH CHECK (
  user_id = auth.uid() AND EXISTS (
    SELECT 1 FROM public.booking_passenger_workflow w
     WHERE w.booking_id = discount_id_submissions.booking_id
       AND w.passenger_id = discount_id_submissions.passenger_id
       AND w.user_id = auth.uid()
       AND w.payment_status = 'awaiting_id'
  )
);

-- Compute the undiscounted fare for one passenger across both legs when applicable.
CREATE OR REPLACE FUNCTION public.calculate_passenger_base_fare(p_booking_id bigint, p_passenger_id bigint)
RETURNS numeric(10,2)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_total numeric(10,2) := 0;
  v_booking public.bookings%ROWTYPE;
  v_outbound numeric(10,2) := 0;
  v_return numeric(10,2) := 0;
BEGIN
  SELECT * INTO v_booking FROM public.bookings WHERE booking_id = p_booking_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found.'; END IF;

  SELECT COALESCE(SUM(ts.fare_from_previous),0)::numeric(10,2)
    INTO v_outbound
    FROM public.train_stops ts
    JOIN public.train_stops dep ON dep.train_id = ts.train_id AND dep.station_id = v_booking.departure_station_id
    JOIN public.train_stops arr ON arr.train_id = ts.train_id AND arr.station_id = v_booking.arrival_station_id
   WHERE ts.train_id = v_booking.train_id
     AND ts.stop_order > dep.stop_order AND ts.stop_order <= arr.stop_order;

  IF v_booking.trip_type = 'round_trip' AND v_booking.return_train_id IS NOT NULL THEN
    SELECT COALESCE(SUM(ts.fare_from_previous),0)::numeric(10,2)
      INTO v_return
      FROM public.train_stops ts
      JOIN public.train_stops dep ON dep.train_id = ts.train_id AND dep.station_id = v_booking.return_departure_station_id
      JOIN public.train_stops arr ON arr.train_id = ts.train_id AND arr.station_id = v_booking.return_arrival_station_id
     WHERE ts.train_id = v_booking.return_train_id
       AND ts.stop_order > dep.stop_order AND ts.stop_order <= arr.stop_order;
  END IF;
  v_total := COALESCE(v_outbound,0) + COALESCE(v_return,0);
  RETURN round(v_total,2);
END;
$$;

REVOKE ALL ON FUNCTION public.calculate_passenger_base_fare(bigint,bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.calculate_passenger_base_fare(bigint,bigint) TO authenticated;

-- Called immediately after the one-way or round-trip booking RPC returns.
CREATE OR REPLACE FUNCTION public.initialize_booking_passenger_workflow(p_booking_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_user uuid := auth.uid();
  v_booking public.bookings%ROWTYPE;
  v_bp record;
  v_base numeric(10,2);
  v_due numeric(10,2);
  v_type text;
  v_discount text;
  v_payment text;
  v_deadline timestamptz;
  v_count integer := 0;
  v_regular_count integer := 0;
  v_discount_count integer := 0;
  v_total numeric(10,2) := 0;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in before continuing.'; END IF;
  SELECT * INTO v_booking FROM public.bookings
   WHERE booking_id = p_booking_id AND user_id = v_user FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found for this account.'; END IF;

  FOR v_bp IN
    SELECT bp.passenger_id, p.passenger_type
      FROM public.booking_passengers bp
      JOIN public.passengers p ON p.passenger_id = bp.passenger_id
     WHERE bp.booking_id = p_booking_id
  LOOP
    v_type := lower(COALESCE(v_bp.passenger_type,'regular'));
    IF v_type NOT IN ('regular','student','senior','pwd') THEN v_type := 'regular'; END IF;
    v_base := public.calculate_passenger_base_fare(p_booking_id, v_bp.passenger_id);
    v_discount := CASE WHEN v_type = 'regular' THEN 'not_required' ELSE 'pending_review' END;
    v_payment := CASE WHEN v_type = 'regular' THEN 'awaiting_payment' ELSE 'awaiting_id' END;
    v_due := CASE WHEN v_type = 'regular' THEN v_base ELSE round(v_base * 0.80,2) END;
    v_deadline := CASE WHEN v_type = 'regular' THEN now() + interval '10 minutes' ELSE NULL END;

    INSERT INTO public.booking_passenger_workflow
      (booking_id,passenger_id,user_id,passenger_type,base_fare,amount_due,discount_status,payment_status,payment_deadline_at,cash_due)
    VALUES
      (p_booking_id,v_bp.passenger_id,v_user,v_type,v_base,v_due,v_discount,v_payment,v_deadline,v_due)
    ON CONFLICT (booking_id,passenger_id) DO UPDATE SET
      passenger_type=EXCLUDED.passenger_type, base_fare=EXCLUDED.base_fare,
      amount_due=EXCLUDED.amount_due, discount_status=EXCLUDED.discount_status,
      payment_status=CASE WHEN booking_passenger_workflow.payment_status IN ('paid','pending_review') THEN booking_passenger_workflow.payment_status ELSE EXCLUDED.payment_status END,
      payment_deadline_at=CASE WHEN booking_passenger_workflow.payment_status IN ('paid','pending_review') THEN booking_passenger_workflow.payment_deadline_at ELSE EXCLUDED.payment_deadline_at END,
      cash_due=CASE WHEN booking_passenger_workflow.payment_status IN ('paid','pending_review') THEN booking_passenger_workflow.cash_due ELSE EXCLUDED.cash_due END,
      updated_at=now();

    v_count := v_count + 1;
    v_total := v_total + v_due;
    IF v_type = 'regular' THEN v_regular_count := v_regular_count + 1; ELSE v_discount_count := v_discount_count + 1; END IF;
  END LOOP;

  IF v_count = 0 THEN RAISE EXCEPTION 'No passengers were found for this booking.'; END IF;
  UPDATE public.bookings SET
    passenger_payment_workflow = true,
    total_fare = v_total,
    booking_status = CASE WHEN v_regular_count > 0 THEN 'pending_payment' ELSE 'pending_discount_verification' END,
    payment_deadline_at = (SELECT MIN(payment_deadline_at) FROM public.booking_passenger_workflow WHERE booking_id=p_booking_id AND payment_status='awaiting_payment')
  WHERE booking_id = p_booking_id;

  RETURN jsonb_build_object('success',true,'passenger_count',v_count,'regular_count',v_regular_count,'discounted_count',v_discount_count,'total_fare',v_total);
END;
$$;
REVOKE ALL ON FUNCTION public.initialize_booking_passenger_workflow(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.initialize_booking_passenger_workflow(bigint) TO authenticated;

-- Each passenger's ID decision starts only that passenger's 10-minute payment window.
CREATE OR REPLACE FUNCTION public.review_discount_id_submission(p_submission_id bigint,p_decision text,p_admin_note text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_role text := public.current_user_role();
  v_sub public.discount_id_submissions%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
  v_flow public.booking_passenger_workflow%ROWTYPE;
  v_new_type text;
  v_new_due numeric(10,2);
  v_title text;
  v_message text;
BEGIN
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN RAISE EXCEPTION 'Only Admin or Super Admin can review discount IDs.'; END IF;
  IF p_decision NOT IN ('approved','rejected') THEN RAISE EXCEPTION 'Decision must be approved or rejected.'; END IF;
  SELECT * INTO v_sub FROM public.discount_id_submissions WHERE discount_submission_id=p_submission_id FOR UPDATE;
  IF NOT FOUND OR v_sub.status <> 'pending_review' THEN RAISE EXCEPTION 'Pending ID submission not found.'; END IF;
  SELECT * INTO v_booking FROM public.bookings WHERE booking_id=v_sub.booking_id FOR UPDATE;
  SELECT * INTO v_flow FROM public.booking_passenger_workflow WHERE booking_id=v_sub.booking_id AND passenger_id=v_sub.passenger_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Passenger payment workflow has not been initialized.'; END IF;

  UPDATE public.discount_id_submissions SET status=p_decision,admin_note=NULLIF(btrim(p_admin_note),''),reviewed_at=now(),reviewed_by=auth.uid(),notification_sent_at=now() WHERE discount_submission_id=p_submission_id;
  IF p_decision='approved' THEN
    v_new_type := v_sub.claimed_type;
    v_new_due := round(v_flow.base_fare * 0.80,2);
    UPDATE public.passengers SET passenger_type=v_new_type WHERE passenger_id=v_sub.passenger_id;
    UPDATE public.booking_passenger_workflow SET passenger_type=v_new_type,amount_due=v_new_due,discount_status='approved',payment_status='awaiting_payment',payment_deadline_at=now()+interval '10 minutes',cash_due=GREATEST(0,v_new_due-jcoins_amount),updated_at=now()
     WHERE workflow_id=v_flow.workflow_id;
    v_title := 'Discount ID approved';
    v_message := 'Your '||upper(v_sub.claimed_type)||' ID was approved. Your 20% discount is applied. You have 10 minutes from this notification to submit payment.';
  ELSE
    v_new_type := 'regular';
    v_new_due := v_flow.base_fare;
    UPDATE public.passengers SET passenger_type='regular' WHERE passenger_id=v_sub.passenger_id;
    UPDATE public.booking_passenger_workflow SET passenger_type='regular',amount_due=v_new_due,discount_status='rejected',payment_status='awaiting_payment',payment_deadline_at=now()+interval '10 minutes',jcoins_amount=0,cash_due=v_new_due,updated_at=now()
     WHERE workflow_id=v_flow.workflow_id;
    v_title := 'Discount ID rejected';
    v_message := 'Your discount ID was rejected. Your passenger type is now Regular (no discount). Your 10-minute payment countdown starts now. '||COALESCE(NULLIF(btrim(p_admin_note),''),'Please proceed to payment.');
  END IF;

  UPDATE public.bookings SET total_fare=(SELECT COALESCE(SUM(amount_due) FILTER (WHERE payment_status <> 'expired'),0) FROM public.booking_passenger_workflow WHERE booking_id=v_sub.booking_id),
    booking_status='pending_payment',
    payment_deadline_at=(SELECT MIN(payment_deadline_at) FROM public.booking_passenger_workflow WHERE booking_id=v_sub.booking_id AND payment_status='awaiting_payment')
  WHERE booking_id=v_sub.booking_id;
  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  VALUES(v_sub.user_id,v_sub.booking_id,v_title,v_message,CASE WHEN p_decision='approved' THEN 'success' ELSE 'warning' END);
  RETURN jsonb_build_object('success',true,'decision',p_decision,'booking_reference',v_booking.booking_reference,'passenger_id',v_sub.passenger_id,'amount_due',v_new_due);
END;
$$;
REVOKE ALL ON FUNCTION public.review_discount_id_submission(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_discount_id_submission(bigint,text,text) TO authenticated;

-- Passenger uploads one receipt for their own fare only.
CREATE OR REPLACE FUNCTION public.submit_passenger_payment_receipt(p_workflow_id bigint,p_receipt_path text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_user uuid:=auth.uid(); v_flow public.booking_passenger_workflow%ROWTYPE; v_sub_id bigint;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in before submitting payment.'; END IF;
  SELECT * INTO v_flow FROM public.booking_passenger_workflow WHERE workflow_id=p_workflow_id AND user_id=v_user FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Passenger payment record not found.'; END IF;
  IF v_flow.payment_status <> 'awaiting_payment' THEN RAISE EXCEPTION 'This passenger is not currently awaiting payment.'; END IF;
  IF v_flow.payment_deadline_at IS NULL OR v_flow.payment_deadline_at <= now() THEN RAISE EXCEPTION 'The 10-minute payment upload period has expired.'; END IF;
  IF p_receipt_path IS NULL OR split_part(p_receipt_path,'/',1) <> v_user::text THEN RAISE EXCEPTION 'Invalid receipt path.'; END IF;
  INSERT INTO public.passenger_payment_submissions(workflow_id,booking_id,passenger_id,user_id,receipt_path,cash_amount,jcoins_amount)
  VALUES(v_flow.workflow_id,v_flow.booking_id,v_flow.passenger_id,v_user,p_receipt_path,v_flow.cash_due,v_flow.jcoins_amount)
  RETURNING submission_id INTO v_sub_id;
  UPDATE public.booking_passenger_workflow SET payment_status='pending_review',payment_deadline_at=NULL,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  SELECT v_user,v_flow.booking_id,'Payment receipt submitted','Your payment receipt has been submitted and is awaiting administrator verification. Your seat will remain reserved while it is being reviewed.','info';
  RETURN jsonb_build_object('success',true,'submission_id',v_sub_id);
END;
$$;
REVOKE ALL ON FUNCTION public.submit_passenger_payment_receipt(bigint,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_passenger_payment_receipt(bigint,text) TO authenticated;

-- Individual JCoins debit. 1 JCoin = PHP 1. Any cash remainder still needs a receipt.
CREATE OR REPLACE FUNCTION public.pay_passenger_with_jcoins(p_workflow_id bigint,p_jcoins_amount numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_user uuid:=auth.uid(); v_flow public.booking_passenger_workflow%ROWTYPE; v_wallet public.jcoins_wallets%ROWTYPE; v_coins numeric(10,2); v_cash numeric(10,2); v_ref text;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in before paying.'; END IF;
  SELECT * INTO v_flow FROM public.booking_passenger_workflow WHERE workflow_id=p_workflow_id AND user_id=v_user FOR UPDATE;
  IF NOT FOUND OR v_flow.payment_status <> 'awaiting_payment' THEN RAISE EXCEPTION 'Passenger is not awaiting payment.'; END IF;
  IF v_flow.payment_deadline_at IS NULL OR v_flow.payment_deadline_at <= now() THEN RAISE EXCEPTION 'Payment window expired.'; END IF;
  IF COALESCE(v_flow.jcoins_amount,0) > 0 THEN
    RETURN jsonb_build_object('success',true,'reused',true,'jcoins_amount',v_flow.jcoins_amount,'cash_due',v_flow.cash_due,'fully_paid',v_flow.payment_status='paid');
  END IF;
  v_coins:=round(COALESCE(p_jcoins_amount,0),2);
  IF v_coins < 0 OR v_coins > v_flow.amount_due THEN RAISE EXCEPTION 'Invalid JCoins amount.'; END IF;
  IF v_coins > 0 THEN
    SELECT * INTO v_wallet FROM public.jcoins_wallets WHERE user_id=v_user FOR UPDATE;
    IF NOT FOUND OR v_wallet.balance < v_coins THEN RAISE EXCEPTION 'Insufficient JCoins balance.'; END IF;
    UPDATE public.jcoins_wallets SET balance=balance-v_coins,total_spent=total_spent+v_coins,updated_at=now() WHERE user_id=v_user RETURNING * INTO v_wallet;
    SELECT booking_reference INTO v_ref FROM public.bookings WHERE booking_id=v_flow.booking_id;
    INSERT INTO public.jcoins_transactions(user_id,transaction_type,direction,amount,balance_after,booking_id,booking_reference,description,idempotency_key,created_by)
    VALUES(v_user,'BOOKING_PAYMENT','debit',v_coins,v_wallet.balance,v_flow.booking_id,v_ref,'Passenger fare payment using JCoins','passenger-payment-'||v_flow.workflow_id::text,v_user)
    ON CONFLICT (idempotency_key) DO NOTHING;
  END IF;
  v_cash:=v_flow.amount_due-v_coins;
  UPDATE public.booking_passenger_workflow SET jcoins_amount=v_coins,cash_due=v_cash,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
  IF v_cash=0 THEN
    UPDATE public.booking_passenger_workflow SET payment_status='paid',payment_deadline_at=NULL,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
    UPDATE public.bookings SET booking_status=CASE WHEN NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_flow.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN 'confirmed' ELSE 'pending_payment' END,
      payment_deadline_at=(SELECT MIN(payment_deadline_at) FROM public.booking_passenger_workflow WHERE booking_id=v_flow.booking_id AND payment_status='awaiting_payment'),
      paid_at=CASE WHEN NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_flow.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN COALESCE(paid_at,now()) ELSE paid_at END
     WHERE booking_id=v_flow.booking_id;
    INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
    VALUES(v_user,v_flow.booking_id,'Passenger paid with JCoins','This passenger fare has been fully paid using JCoins.','success');
  END IF;
  RETURN jsonb_build_object('success',true,'jcoins_amount',v_coins,'cash_due',v_cash,'fully_paid',v_cash=0);
END;
$$;
REVOKE ALL ON FUNCTION public.pay_passenger_with_jcoins(bigint,numeric) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pay_passenger_with_jcoins(bigint,numeric) TO authenticated;

-- Admin/Superadmin receipt review; pending admin review never expires a passenger seat.
CREATE OR REPLACE FUNCTION public.review_passenger_payment_submission(p_submission_id bigint,p_decision text,p_admin_note text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_role text:=public.current_user_role(); v_sub public.passenger_payment_submissions%ROWTYPE; v_flow public.booking_passenger_workflow%ROWTYPE; v_booking public.bookings%ROWTYPE; v_msg text;
BEGIN
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN RAISE EXCEPTION 'Only Admin or Super Admin can review payments.'; END IF;
  IF p_decision NOT IN ('approved','rejected') THEN RAISE EXCEPTION 'Decision must be approved or rejected.'; END IF;
  SELECT * INTO v_sub FROM public.passenger_payment_submissions WHERE submission_id=p_submission_id FOR UPDATE;
  IF NOT FOUND OR v_sub.status<>'pending_review' THEN RAISE EXCEPTION 'Pending payment submission not found.'; END IF;
  SELECT * INTO v_flow FROM public.booking_passenger_workflow WHERE workflow_id=v_sub.workflow_id FOR UPDATE;
  SELECT * INTO v_booking FROM public.bookings WHERE booking_id=v_sub.booking_id FOR UPDATE;
  UPDATE public.passenger_payment_submissions SET status=p_decision,admin_note=NULLIF(btrim(p_admin_note),''),reviewed_at=now(),reviewed_by=auth.uid() WHERE submission_id=p_submission_id;
  IF p_decision='approved' THEN
    UPDATE public.booking_passenger_workflow SET payment_status='paid',payment_deadline_at=NULL,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
    v_msg:='Your payment receipt for '||v_booking.booking_reference||' was approved.';
    UPDATE public.booking_payments SET payment_status='completed',amount=v_sub.cash_amount,completed_at=COALESCE(completed_at,now()),updated_at=now()
     WHERE payment_id=(SELECT payment_id FROM public.booking_payments WHERE booking_id=v_sub.booking_id ORDER BY created_at DESC,payment_id DESC LIMIT 1);
  ELSE
    IF COALESCE(v_flow.jcoins_amount,0) > 0 THEN
      UPDATE public.jcoins_wallets SET balance=balance+v_flow.jcoins_amount,total_spent=GREATEST(0,total_spent-v_flow.jcoins_amount),updated_at=now() WHERE user_id=v_sub.user_id;
      INSERT INTO public.jcoins_transactions(user_id,transaction_type,direction,amount,balance_after,booking_id,booking_reference,description,idempotency_key,created_by)
      SELECT v_sub.user_id,'BOOKING_PAYMENT_REVERSAL','credit',v_flow.jcoins_amount,w.balance,v_sub.booking_id,b.booking_reference,'JCoins returned because passenger receipt was rejected','passenger-payment-reversal-'||v_sub.submission_id::text,v_sub.user_id
        FROM public.jcoins_wallets w JOIN public.bookings b ON b.booking_id=v_sub.booking_id WHERE w.user_id=v_sub.user_id
      ON CONFLICT (idempotency_key) DO NOTHING;
    END IF;
    UPDATE public.booking_passenger_workflow SET payment_status='awaiting_payment',payment_deadline_at=now()+interval '10 minutes',jcoins_amount=0,cash_due=amount_due,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
    v_msg:='Your payment receipt was rejected. '||COALESCE(NULLIF(btrim(p_admin_note),''),'Please upload a corrected receipt.')||' Any JCoins used have been returned. You have 10 minutes from this notification to submit a new receipt.';
  END IF;
  UPDATE public.bookings SET
    total_fare=(SELECT COALESCE(SUM(amount_due) FILTER (WHERE payment_status <> 'expired'),0) FROM public.booking_passenger_workflow WHERE booking_id=v_sub.booking_id),
    booking_status=CASE WHEN NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_sub.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN 'confirmed' ELSE 'pending_payment' END,
    payment_deadline_at=(SELECT MIN(payment_deadline_at) FROM public.booking_passenger_workflow WHERE booking_id=v_sub.booking_id AND payment_status='awaiting_payment'),
    paid_at=CASE WHEN NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_sub.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN COALESCE(paid_at,now()) ELSE paid_at END
  WHERE booking_id=v_sub.booking_id;
  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  VALUES(v_sub.user_id,v_sub.booking_id,CASE WHEN p_decision='approved' THEN 'Payment approved' ELSE 'Payment receipt rejected' END,v_msg,CASE WHEN p_decision='approved' THEN 'success' ELSE 'warning' END);
  RETURN jsonb_build_object('success',true,'decision',p_decision,'booking_reference',v_booking.booking_reference);
END;
$$;
REVOKE ALL ON FUNCTION public.review_passenger_payment_submission(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_passenger_payment_submission(bigint,text,text) TO authenticated;

-- Expire only the individual unpaid passenger whose own deadline elapsed. Never expire
-- an ID-pending passenger or a receipt already submitted for admin review.
CREATE OR REPLACE FUNCTION public.expire_passenger_payment_holds()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_flow record; v_count integer:=0; v_remaining integer; v_total numeric(10,2);
BEGIN
  FOR v_flow IN
    SELECT * FROM public.booking_passenger_workflow
     WHERE payment_status='awaiting_payment' AND payment_deadline_at IS NOT NULL AND payment_deadline_at <= now()
     FOR UPDATE SKIP LOCKED
  LOOP
    IF COALESCE(v_flow.jcoins_amount,0) > 0 THEN
      UPDATE public.jcoins_wallets SET balance=balance+v_flow.jcoins_amount,total_spent=GREATEST(0,total_spent-v_flow.jcoins_amount),updated_at=now()
       WHERE user_id=v_flow.user_id;
      INSERT INTO public.jcoins_transactions(user_id,transaction_type,direction,amount,balance_after,booking_id,booking_reference,description,idempotency_key,created_by)
      SELECT v_flow.user_id,'BOOKING_PAYMENT_REVERSAL','credit',v_flow.jcoins_amount,w.balance,v_flow.booking_id,b.booking_reference,
             'JCoins returned because the passenger payment window expired','passenger-expiry-reversal-'||v_flow.workflow_id::text,v_flow.user_id
        FROM public.jcoins_wallets w JOIN public.bookings b ON b.booking_id=v_flow.booking_id
       WHERE w.user_id=v_flow.user_id
      ON CONFLICT (idempotency_key) DO NOTHING;
    END IF;
    DELETE FROM public.booking_passengers WHERE booking_id=v_flow.booking_id AND passenger_id=v_flow.passenger_id;
    DELETE FROM public.booking_return_passengers WHERE booking_id=v_flow.booking_id AND passenger_id=v_flow.passenger_id;
    UPDATE public.booking_passenger_workflow SET payment_status='expired',payment_deadline_at=NULL,updated_at=now() WHERE workflow_id=v_flow.workflow_id;
    SELECT COUNT(*) INTO v_remaining FROM public.booking_passenger_workflow WHERE booking_id=v_flow.booking_id AND payment_status<>'expired';
    SELECT COALESCE(SUM(amount_due),0) INTO v_total FROM public.booking_passenger_workflow WHERE booking_id=v_flow.booking_id AND payment_status<>'expired';
    UPDATE public.bookings SET total_passengers=v_remaining,total_fare=v_total,
      booking_status=CASE WHEN v_remaining=0 THEN 'expired'
        WHEN NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_flow.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN 'confirmed'
        WHEN EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_flow.booking_id AND x.payment_status='awaiting_id') THEN 'pending_discount_verification'
        ELSE 'pending_payment' END,
      payment_deadline_at=(SELECT MIN(payment_deadline_at) FROM public.booking_passenger_workflow WHERE booking_id=v_flow.booking_id AND payment_status='awaiting_payment'),
      paid_at=CASE WHEN v_remaining>0 AND NOT EXISTS (SELECT 1 FROM public.booking_passenger_workflow x WHERE x.booking_id=v_flow.booking_id AND x.payment_status NOT IN ('paid','expired')) THEN COALESCE(paid_at,now()) ELSE paid_at END
     WHERE booking_id=v_flow.booking_id;
    INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
    VALUES(v_flow.user_id,v_flow.booking_id,'Passenger reservation expired','The 10-minute payment period expired for one passenger. Only that passenger seat was released; the other passengers remain reserved.','warning');
    v_count:=v_count+1;
  END LOOP;
  RETURN v_count;
END;
$$;
REVOKE ALL ON FUNCTION public.expire_passenger_payment_holds() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.expire_passenger_payment_holds() TO service_role;

-- Legacy booking-wide expiry must ignore reservations managed by the passenger workflow.
CREATE OR REPLACE FUNCTION public.expire_pending_bookings()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.bookings AS b SET booking_status='expired'
   WHERE b.booking_status='pending_payment' AND b.passenger_payment_workflow=false
     AND b.payment_deadline_at IS NOT NULL AND b.payment_deadline_at<=now()
     AND NOT EXISTS (SELECT 1 FROM public.payment_submissions ps WHERE ps.booking_id=b.booking_id AND ps.status='pending_review');
  GET DIAGNOSTICS v_count=ROW_COUNT;
  RETURN v_count;
END;
$$;
REVOKE ALL ON FUNCTION public.expire_pending_bookings() FROM PUBLIC, authenticated;
GRANT EXECUTE ON FUNCTION public.expire_pending_bookings() TO service_role;

